/* Gallery behaviour for the pages that have one: tap to open, swipe or arrow to move,
   related photographs by tag, and ?tag= filtering. No library. The markup it reads is
   generated by tools/photos.py — figures carry an id and a data-tags list. */
(function () {
  var grid = document.querySelector('.gallery-grid');
  if (!grid) return;

  var all = [].slice.call(document.querySelectorAll('.gallery-grid .photo-card'));
  var withImg = all.filter(function (f) { return f.querySelector('img'); });
  // `figures` is the set the lightbox is currently moving through. It is rescoped to
  // one album the moment a photograph in that album is clicked, so swiping never
  // walks out of the set you opened.
  var figures = withImg;

  function tagsOf(fig) {
    var raw = fig.getAttribute('data-tags') || '';
    return raw ? raw.split(',') : [];
  }

  /* ---------- ?tag= filter ---------------------------------------------------- */
  var active = new URLSearchParams(location.search).get('tag');
  if (active) {
    all.forEach(function (f) {
      f.hidden = tagsOf(f).indexOf(active) === -1;
    });
    // An album with nothing left in it must go away entirely — otherwise the page
    // is seven covers over seven empty grids. The ones that do still hold something
    // are opened, because a filtered page with every album shut shows nothing.
    document.querySelectorAll('.album, .gallery-wrap').forEach(function (sec) {
      var cards = [].slice.call(sec.querySelectorAll('.photo-card'));
      if (!cards.length) return;
      var shown = cards.filter(function (c) { return !c.hidden; }).length;
      if (!shown) { sec.hidden = true; return; }
      sec.open = true;
      // The cover's count is rendered as the album's total. Under a filter that
      // total is not what is on screen, so it has to be restated — otherwise the
      // cover says 5 while the grid under it holds 4.
      var label = sec.querySelector('.album-eyebrow');
      if (label) label.textContent = shown + ' photograph' + (shown === 1 ? '' : 's');
    });
    withImg = withImg.filter(function (f) { return !f.hidden; });
    figures = withImg;
    document.querySelectorAll('.tag-chip').forEach(function (c) {
      c.classList.toggle('is-on', c.getAttribute('data-tag') === active);
    });
  }
  /* ---------- album bar ---------------------------------------------------------
     Each chip names one album below and opens it, closing the others, so the page
     stays one album long instead of seven. "everything" shuts them all and gives
     the seven covers back — that is the page's resting state, not a wall of 29
     photographs. Runs before the lightbox sets up, so the bar still works on a
     browser with no <dialog>. */
  var chips = [].slice.call(document.querySelectorAll('.tag-chip[data-album]'));
  var albums = [].slice.call(document.querySelectorAll('.album'));
  if (chips.length && albums.length) {
    // One function for both the click and the URL, so they cannot drift apart.
    // Clicking and arriving at #school have to leave the page in the same state.
    function showAlbum(key) {
      var chip = chips.filter(function (c) {
        return c.getAttribute('data-album') === (key || '');
      })[0];
      // A photograph deep-link such as #school-meal is not an album. The lightbox
      // code further down handles it; this must not shut the album it opens.
      if (key && !chip) return null;
      var target = key ? document.getElementById(key) : null;
      albums.forEach(function (a) { a.open = a === target; });
      chips.forEach(function (c) { c.classList.toggle('is-on', c === chip); });
      return target;
    }

    chips.forEach(function (chip) {
      chip.addEventListener('click', function (e) {
        e.preventDefault();
        var key = chip.getAttribute('data-album');
        var target = showAlbum(key);
        // Scrolling to the album is what makes the tap feel like it did something
        // on a phone, where the album itself starts below the fold.
        (target || document.querySelector('.tag-bar')).scrollIntoView({ block: 'start' });
        history.replaceState(null, '', key ? '#' + key : location.pathname);
      });
    });

    // On load, and on hashchange — moving to #market from this same page is a
    // fragment navigation, so the script never runs again. Without this the back
    // button changes the URL and nothing else.
    showAlbum(location.hash.slice(1));
    addEventListener('hashchange', function () { showAlbum(location.hash.slice(1)); });
  }

  if (!figures.length || !window.HTMLDialogElement) return;

  /* ---------- lightbox --------------------------------------------------------- */
  var dlg = document.createElement('dialog');
  dlg.className = 'lightbox';
  dlg.innerHTML =
    '<button class="lb-nav lb-prev" type="button" aria-label="Previous photograph">&#8249;</button>' +
    '<figure class="lb-frame"><img alt=""><figcaption></figcaption>' +
    '<p class="lb-also"></p></figure>' +
    '<button class="lb-nav lb-next" type="button" aria-label="Next photograph">&#8250;</button>' +
    '<button class="lb-close" type="button" aria-label="Close">&times;</button>';
  document.body.appendChild(dlg);

  var img = dlg.querySelector('img');
  var cap = dlg.querySelector('figcaption');
  var also = dlg.querySelector('.lb-also');
  var at = 0;

  function related(i) {
    var mine = tagsOf(figures[i]);
    if (!mine.length) return [];
    return figures
      .map(function (f, j) {
        if (j === i) return null;
        var shared = tagsOf(f).filter(function (t) { return mine.indexOf(t) > -1; }).length;
        return shared ? { j: j, shared: shared } : null;
      })
      .filter(Boolean)
      .sort(function (a, b) { return b.shared - a.shared; })
      .slice(0, 3);
  }

  function show(i, dir) {
    at = (i + figures.length) % figures.length;          // wraps both ways
    var src = figures[at].querySelector('img');
    var fc = figures[at].querySelector('figcaption');
    img.src = src.currentSrc || src.src;
    img.alt = src.alt;
    cap.textContent = fc ? fc.textContent : '';

    also.textContent = '';
    var near = related(at);
    if (near.length) {
      also.appendChild(document.createTextNode('also: '));
      near.forEach(function (n, k) {
        var b = document.createElement('button');
        b.type = 'button';
        b.textContent = figures[n.j].querySelector('figcaption').textContent;
        b.addEventListener('click', function () { show(n.j, 1); });
        also.appendChild(b);
        if (k < near.length - 1) also.appendChild(document.createTextNode(' · '));
      });
    }

    // Restart the slide-in. Removing the class and reading offsetWidth forces the
    // reflow that lets the same animation play again on the next photograph.
    img.classList.remove('lb-in-left', 'lb-in-right');
    if (dir) { void img.offsetWidth; img.classList.add(dir < 0 ? 'lb-in-left' : 'lb-in-right'); }
  }

  function open(i) {
    show(i);
    if (!dlg.open) dlg.showModal();
    // replaceState, not a hash assignment: opening ten photographs should not leave
    // ten entries in the back button. The URL still copies and shares correctly.
    history.replaceState(null, '', '#' + figures[at].id);
  }
  function prev() { show(at - 1, -1); }
  function next() { show(at + 1, 1); }

  function openFrom(fig) {
    // Scope to the album this photograph belongs to, falling back to the whole page
    // when there are no albums (land.html once had a flat grid; days.html has none).
    var album = fig.closest('.album');
    figures = album
      ? withImg.filter(function (f) { return album.contains(f); })
      : withImg;
    open(figures.indexOf(fig));
  }

  withImg.forEach(function (fig) {
    fig.addEventListener('click', function () { openFrom(fig); });
    fig.addEventListener('keydown', function (e) {
      // The figure carries role="button", so it has to answer to a keyboard like one.
      if (e.key === 'Enter' || e.key === ' ') { e.preventDefault(); openFrom(fig); }
    });
  });

  dlg.querySelector('.lb-prev').addEventListener('click', prev);
  dlg.querySelector('.lb-next').addEventListener('click', next);
  dlg.querySelector('.lb-close').addEventListener('click', function () { dlg.close(); });
  dlg.addEventListener('keydown', function (e) {
    if (e.key === 'ArrowLeft') prev();
    if (e.key === 'ArrowRight') next();
  });
  // Clicking the dark area around the photo closes it. The frame and the buttons
  // sit inside their own elements, so this only fires on the dialog's own padding.
  dlg.addEventListener('click', function (e) { if (e.target === dlg) dlg.close(); });
  dlg.addEventListener('close', function () {
    figures[at].focus();
    history.replaceState(null, '', location.pathname + location.search);
  });

  // Swipe. One finger only — two fingers is a pinch-zoom on the photograph, and
  // stealing that would make the big view useless on a phone.
  var x0 = null, y0 = null;
  dlg.addEventListener('touchstart', function (e) {
    if (e.touches.length !== 1) { x0 = null; return; }
    x0 = e.touches[0].clientX;
    y0 = e.touches[0].clientY;
  }, { passive: true });
  dlg.addEventListener('touchend', function (e) {
    if (x0 === null) return;
    var dx = e.changedTouches[0].clientX - x0;
    var dy = e.changedTouches[0].clientY - y0;
    // Horizontal intent only, so a vertical scroll-to-dismiss gesture is not read
    // as a swipe. 45px is about a thumb's width of deliberate movement.
    if (Math.abs(dx) > 45 && Math.abs(dx) > Math.abs(dy)) { dx < 0 ? next() : prev(); }
    x0 = null;
  }, { passive: true });

  // Arriving on photographs.html#school-meal opens that photograph. This is what
  // makes a written piece able to link one frame instead of a whole page.
  if (location.hash) {
    var want = document.getElementById(location.hash.slice(1));
    if (want && withImg.indexOf(want) > -1) {
      var album = want.closest('.album');
      if (album) album.open = true;      // a link into a shut album has to open it
      openFrom(want);
    }
  }
})();
